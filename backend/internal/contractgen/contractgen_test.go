// A type both contracts define (PermissionMode, SessionStatus, Answer, ...) must be the same in both: the API
// passes them through to and from events.
func TestSharedTypesAgree(t *testing.T) {
	ev, err := Load(repoRoot, EventsSchema)
	if err != nil {
		t.Fatal(err)
	}
	api, err := Load(repoRoot, OpenAPISpec)
	if err != nil {
		t.Fatal(err)
	}
	shared := 0
	for _, name := range ev.Names() {
		a, ok := api.Defs[name]
		if !ok {
			continue
		}
		shared++
		e := ev.Defs[name]
		if strings.Join(e.Enum, ",") != strings.Join(a.Enum, ",") {
			t.Errorf("%s: enum %v in the events schema, %v in the API", name, e.Enum, a.Enum)
		}
		if strings.Join(e.Order, ",") != strings.Join(a.Order, ",") || strings.Join(e.Required, ",") != strings.Join(a.Required, ",") {
			t.Errorf("%s: properties %v (required %v) in the events schema, %v (%v) in the API", name, e.Order,
				e.Required, a.Order, a.Required)
		}
	}
	if shared < 5 {
		t.Errorf("only %d shared types: the check is not looking at the real contracts", shared)
	}
}

