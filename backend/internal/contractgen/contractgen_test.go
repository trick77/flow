func TestGolden_writesWithUpdateAndReportsStale(t *testing.T) {
	dir := t.TempDir()
	tg := []Target{{Out: "a/b.txt", Render: func() ([]byte, error) { return []byte("one\ntwo\n"), nil }}}
	t.Setenv(UpdateEnv, "1")
	Golden(t, dir, tg)
	b, err := os.ReadFile(filepath.Join(dir, "a", "b.txt"))
	if err != nil || string(b) != "one\ntwo\n" {
		t.Fatalf("update wrote %q, %v", b, err)
	}
	t.Setenv(UpdateEnv, "")
	if err := os.WriteFile(filepath.Join(dir, "a", "b.txt"), []byte("one\nthree\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	ft := &fakeTB{TB: t}
	Golden(ft, dir, tg)
	if !strings.Contains(ft.msg, "line 2") {
		t.Errorf("stale message = %q, want the first differing line", ft.msg)
	}
	ft = &fakeTB{TB: t}
	Golden(ft, filepath.Join(dir, "missing"), tg)
	if !strings.Contains(ft.msg, "no such file") {
		t.Errorf("missing message = %q", ft.msg)
	}
	if _, err := Targets(dir); err == nil {
		t.Error("Targets of an empty tree succeeded")
	}
	if _, err := Load(repoRoot, OpenAPISpec); err != nil {
		t.Error(err)
	}
}

