func TestLoad_refusesWhatTheBindingsCannotExpress(t *testing.T) {
	for name, c := range map[string]struct{ doc, want string }{
		"keyword":       {`{"$defs":{"A":{"type":"object","oneOf":[]}}}`, `unsupported keyword "oneOf"`},
		"inline enum":   {`{"$defs":{"A":{"type":"object","properties":{"x":{"type":"string","enum":["a"]}}}}}`, "inline enum"},
		"inline object": {`{"$defs":{"A":{"type":"object","properties":{"x":{"type":"object","properties":{"y":{}}}}}}}`, "inline object"},
		"dangling ref":  {`{"$defs":{"A":{"type":"object","properties":{"x":{"$ref":"#/$defs/B"}}}}}`, "undefined"},
		"foreign ref":   {`{"$defs":{"A":{"type":"object","properties":{"x":{"$ref":"other.json#/A"}}}}}`, "only #/$defs/"},
		"required":      {`{"$defs":{"A":{"type":"object","required":["z"],"properties":{}}}}`, `required "z"`},
		"named scalar":  {`{"$defs":{"A":{"type":"string"}}}`, "object or a string enum"},
		"named map":     {`{"$defs":{"A":{"type":"object","additionalProperties":{"type":"string"}}}}`, "named map"},
		"array":         {`{"$defs":{"A":{"type":"object","properties":{"x":{"type":"array"}}}}}`, "without items"},
		"type":          {`{"$defs":{"A":{"type":"object","properties":{"x":{"type":"null"}}}}}`, `unsupported type "null"`},
		"no defs":       {`{}`, "no type definitions"},
		"bad union":     {`{"x-unions":{"U":{"envelope":"E","kinds":[{"kind":"k","payload":"P"},{"kind":"k","payload":"A"}]}},"$defs":{"A":{"type":"object"}}}`, `type "E" undefined`},
		"not json":      {`{`, "unexpected end"},
		"bad props":     {`{"$defs":{"A":{"type":"object","properties":[]}}}`, "cannot unmarshal"},
		"bad addl":      {`{"$defs":{"A":{"type":"object","properties":{"m":{"type":"object","additionalProperties":{"x":1}}}}}}`, "additionalProperties"},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := LoadEvents("x.json", []byte(c.doc))
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("err = %v, want %q", err, c.want)
			}
		})
	}
}

func TestLoadOpenAPI_readsComponentSchemas(t *testing.T) {
	doc := `{"openapi":"3.1.0","components":{"schemas":{
		"Error":{"type":"object","required":["code"],"properties":{"code":{"$ref":"#/components/schemas/Code"}}},
		"Code":{"type":"string","enum":["not_implemented"]}}}}`
	d, err := LoadOpenAPI("api.json", []byte(doc))
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(d.Names(), ","); got != "Error,Code" {
		t.Errorf("names = %s, want source order", got)
	}
	if err := d.Validate("Error", []byte(`{"code":"not_implemented"}`)); err != nil {
		t.Error(err)
	}
	if _, err := LoadOpenAPI("api.json", []byte(`{"components":{}}`)); err == nil {
		t.Error("an OpenAPI document without schemas loaded")
	}
	if _, err := LoadOpenAPI("api.json", []byte(`[`)); err == nil {
		t.Error("broken JSON loaded")
	}
}

func TestValidate(t *testing.T) {
	d := loadTiny(t)
	ok := `{"kind":"a.done","at":"2026-11-26T14:18:03.12Z","data":{"toolId":"t1","colors":["blue"],"n":3,
		"small":1,"ratio":0.5,"ok":true,"tags":{"a":"b"},"nested":{},"list":[["x"]]}}`
	if err := d.ValidateUnion("Msg", []byte(ok)); err != nil {
		t.Errorf("valid value refused: %v", err)
	}
	for name, c := range map[string]struct{ def, value, want string }{
		"missing":     {"ADone", `{"colors":[],"n":1}`, `missing "toolId"`},
		"unknown":     {"ADone", `{"toolId":"t","colors":[],"n":1,"x":1}`, `unknown field "x"`},
		"enum":        {"ADone", `{"toolId":"t","colors":["green"],"n":1}`, "not one of"},
		"integer":     {"ADone", `{"toolId":"t","colors":[],"n":1.5}`, "not an integer"},
		"int type":    {"ADone", `{"toolId":"t","colors":[],"n":"1"}`, "want an integer"},
		"number":      {"ADone", `{"toolId":"t","colors":[],"n":1,"ratio":"x"}`, "want a number"},
		"bool":        {"ADone", `{"toolId":"t","colors":[],"n":1,"ok":1}`, "want a boolean"},
		"string":      {"ADone", `{"toolId":1,"colors":[],"n":1}`, "want a string"},
		"array":       {"ADone", `{"toolId":"t","colors":{},"n":1}`, "want an array"},
		"object":      {"ADone", `[]`, "want an object"},
		"map value":   {"ADone", `{"toolId":"t","colors":[],"n":1,"tags":{"a":1}}`, "want a string"},
		"date":        {"Msg", `{"kind":"b","data":{},"at":"yesterday"}`, "not RFC 3339"},
		"unknown def": {"Nope", `{}`, "unknown type"},
		"bad json":    {"ADone", `{`, "unexpected EOF"},
	} {
		t.Run(name, func(t *testing.T) {
			err := d.Validate(c.def, []byte(c.value))
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("err = %v, want %q", err, c.want)
			}
		})
	}
	for name, c := range map[string]struct{ union, value, want string }{
		"union":    {"Nope", `{}`, "unknown union"},
		"kind":     {"Msg", `{"kind":"c","data":{},"at":"2026-11-26T14:18:03Z"}`, `unknown MsgKind "c"`},
		"envelope": {"Msg", `{"kind":"b"}`, `missing "at"`},
		"payload":  {"Msg", `{"kind":"a.done","data":{},"at":"2026-11-26T14:18:03Z"}`, "data:"},
	} {
		t.Run(name, func(t *testing.T) {
			err := d.ValidateUnion(c.union, []byte(c.value))
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("err = %v, want %q", err, c.want)
			}
		})
	}
	if k, ok := d.KindOf("Msg", "b"); !ok || !k.Sidecar {
		t.Errorf("KindOf(Msg, b) = %+v, %v", k, ok)
	}
	if _, ok := d.KindOf("Msg", "zz"); ok {
		t.Error("KindOf found an unknown kind")
	}
}

