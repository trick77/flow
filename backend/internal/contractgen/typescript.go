package contractgen

import (
	"bytes"
	"fmt"
	"strings"
)

// TSHeader starts every generated TypeScript file. The files are listed in .prettierignore; eslint checks them.
const TSHeader = "// Code generated by contractgen from %s. DO NOT EDIT.\n// Regenerate: %s\n"

// TS renders the doc's types as one TypeScript module of types and kind lists.
func (d *Doc) TS() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, TSHeader, d.Source, Regenerate)
	kindOverride := d.kindTypes()
	for _, name := range d.Names() {
		s := d.Defs[name]
		b.WriteString("\n")
		tsDoc(&b, "", s.Description)
		if s.Type == "string" {
			quoted := make([]string, len(s.Enum))
			for i, v := range s.Enum {
				quoted[i] = fmt.Sprintf("%q", v)
			}
			fmt.Fprintf(&b, "export type %s = %s;\n", name, strings.Join(quoted, " | "))
			fmt.Fprintf(&b, "export const %s_VALUES: readonly %s[] = [%s];\n", constName(name), name,
				strings.Join(quoted, ", "))
			continue
		}
		if len(s.Order) == 0 {
			fmt.Fprintf(&b, "export type %s = Record<string, never>;\n", name)
			continue
		}
		fmt.Fprintf(&b, "export interface %s {\n", name)
		for _, p := range s.Order {
			ps := s.Properties[p]
			typ, err := d.tsType(ps)
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %w", name, p, err)
			}
			if kt, ok := kindOverride[name]; ok && p == "kind" {
				typ = kt
			}
			tsDoc(&b, "  ", ps.Description)
			opt := "?"
			if s.isRequired(p) {
				opt = ""
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", p, opt, typ)
		}
		b.WriteString("}\n")
	}
	for _, u := range d.Unions {
		tsUnion(&b, u)
	}
	return b.Bytes(), nil
}

func tsUnion(b *bytes.Buffer, u Union) {
	payloads := u.Name + "Payloads"
	fmt.Fprintf(b, "\n/** The payload type of each %s. */\nexport interface %s {\n", u.KindType, payloads)
	var all, eph, side []string
	for _, k := range u.Kinds {
		fmt.Fprintf(b, "  %q: %s;\n", k.Kind, k.Payload)
		q := fmt.Sprintf("%q", k.Kind)
		all = append(all, q)
		if k.Ephemeral {
			eph = append(eph, q)
		}
		if k.Sidecar {
			side = append(side, q)
		}
	}
	b.WriteString("}\n")
	fmt.Fprintf(b, "\nexport type %s = keyof %s;\n", u.KindType, payloads)
	fmt.Fprintf(b, "\n/** %s with data typed by its kind. */\n", u.Envelope)
	fmt.Fprintf(b, "export type Typed%s = {\n  [K in %s]: Omit<%s, \"kind\" | \"data\"> & {\n    kind: K;\n    data: %s[K];\n  };\n}[%s];\n",
		u.Name, u.KindType, u.Envelope, payloads, u.KindType)
	writeList := func(name string, items []string) {
		if len(items) == 0 {
			fmt.Fprintf(b, "\nexport const %s: readonly %s[] = [];\n", name, u.KindType)
			return
		}
		fmt.Fprintf(b, "\nexport const %s: readonly %s[] = [\n", name, u.KindType)
		for _, it := range items {
			fmt.Fprintf(b, "  %s,\n", it)
		}
		b.WriteString("];\n")
	}
	writeList(constName(u.KindType)+"S", all)
	writeList("EPHEMERAL_"+constName(u.KindType)+"S", eph)
	writeList("SIDECAR_"+constName(u.KindType)+"S", side)
}

func (d *Doc) tsType(s *Schema) (string, error) {
	switch {
	case s.Ref != "":
		return d.resolve(s.Ref)
	case s.Type == "array":
		t, err := d.tsType(s.Items)
		if strings.Contains(t, " ") {
			return "(" + t + ")[]", err
		}
		return t + "[]", err
	case s.Type == "object":
		t, err := d.tsType(s.Values)
		return "Record<string, " + t + ">", err
	case s.Type == "string":
		return "string", nil
	case s.Type == "integer", s.Type == "number":
		return "number", nil
	case s.Type == "boolean":
		return "boolean", nil
	case s.Type == "":
		return "unknown", nil
	}
	return "", fmt.Errorf("unsupported type %q", s.Type)
}

func tsDoc(b *bytes.Buffer, indent, desc string) {
	if desc == "" {
		return
	}
	desc = strings.ReplaceAll(desc, "*/", "* /")
	lines := wrap(desc, 100)
	if len(lines) == 1 {
		fmt.Fprintf(b, "%s/** %s */\n", indent, lines[0])
		return
	}
	fmt.Fprintf(b, "%s/**\n", indent)
	for _, l := range lines {
		fmt.Fprintf(b, "%s * %s\n", indent, l)
	}
	fmt.Fprintf(b, "%s */\n", indent)
}
